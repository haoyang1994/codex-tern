import { spawn, execFileSync } from 'node:child_process';
import { mkdir, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { resolve } from 'node:path';
import assert from 'node:assert/strict';
import { prepareTernQaConfig } from './qa-tern-config.mjs';
const root = resolve(import.meta.dirname, '..'), out = resolve(root, '.prototype/usage-qa');
await mkdir(out, {recursive:true});
const config = resolve(out, `config-${process.pid}`), socket = `/tmp/ct-usage-${process.pid}.sock`, daemonSocket = `/tmp/ct-usage-daemon-${process.pid}.sock`;
await prepareTernQaConfig(config);
const env = {...process.env, TERN_CONFIG_DIR: config, TERN_DAEMON_SOCKET: daemonSocket, XDG_STATE_HOME: resolve(out,`state-${process.pid}`), XDG_CACHE_HOME: resolve(out,`cache-${process.pid}`), QA_HISTORY_FILE: resolve(out,`history-${process.pid}.json`)};
delete env.TERN_WINDOW_KEY; delete env.TERN_WINDOW_SOCKET;
const daemon = spawn('tern', ['daemon','--socket',daemonSocket], {env,stdio:'ignore'});
let server;
const ctl = cmd => {const r=JSON.parse(execFileSync('tern',['ctl','--control',socket,cmd],{env,encoding:'utf8',timeout:5000})); if (!r.ok) throw Error(JSON.stringify(r)); return r;};
const nodes = sel => ctl(`tree ${sel}`).nodes ?? [];
const wait = async (fn,desc) => {for(let i=0;i<150;i++){try{if(fn())return;}catch{} await new Promise(r=>setTimeout(r,100));} throw Error(`Timed out ${desc}`);};
try {
 await wait(()=>existsSync(daemonSocket),'daemon');
 server=spawn('tern',['serve','--control',socket,'--out',out,'--cwd',root],{env,stdio:'ignore'});
 await wait(()=>existsSync(socket),'serve');
 const q=s=>"'"+s.replaceAll("'","'\\''")+"'";
 const cmd=['env',`QA_HISTORY_FILE=${env.QA_HISTORY_FILE}`,process.execPath,resolve(root,'dist/cli.mjs'),'--codex',resolve(root,'test/fixtures/ui-app-server.mjs')].map(q).join(' ');
 ctl(`run ${JSON.stringify(cmd)}`);
 await wait(()=>nodes('[data-role="omp.editor"] .sf-editor').length,'composer');
 ctl('type "QA_CONTEXT_NOTIFY"'); ctl('key Enter');
 await wait(()=>nodes('[data-role="ct.turn.metrics"]').length===1,'status metrics');
 const metrics=nodes('[data-role="ct.turn.metrics"]')[0];
 const status=nodes('[data-role="omp.status"]')[0];
 assert.ok(metrics.text.includes('8.3%') && metrics.text.includes('50.0 t/s'), JSON.stringify(metrics));
 assert.equal(nodes('[data-role="ct.reply.usage"]').length,0);
 const entries=nodes('[data-role="omp.status"] .sf-seg');
 const notice=entries.find(n => n.text?.includes('Notice'));
 assert.ok(notice && metrics.rect[0]+metrics.rect[2]<=notice.rect[0], JSON.stringify({metrics,notice,status}));
 console.log('PASS status metrics are left of Notice and reply footer has no numeric usage');
 ctl('key Control+q');
 await wait(()=>!!ctl('state').focused?.prompt,'client closed');
 ctl('ready');
 ctl(`run ${JSON.stringify(cmd)}`);
 await wait(()=>nodes('[data-role="ct.turn.metrics"]').length===1,'restored usage label');
 assert.ok(nodes('[data-role="ct.turn.metrics"]')[0].text.includes('8.3%'));
 console.log('PASS completed turn usage survives client restart');
} finally {try{ctl('quit');}catch{} server?.kill(); daemon.kill();}
