export function translate(language: Language | undefined, text: string): string {
  if (language !== 'zh-CN') return text;
  if (zhCN[text] !== undefined) return zhCN[text]!;
  for (const [pattern, render] of [
    [/^Unknown command: (.+)$/, (value: string) => `未知命令：${value}`],
    [/^Command available in --plain: (.+)$/, (value: string) => `此命令仅在 --plain 模式可用：${value}`],
    [/^Usage: (.+)$/, (value: string) => `用法：${value}`],
    [/^Choose a path for (.+) in \/skills\.$/, (value: string) => `请在 /skills 中为 ${value} 选择准确路径。`],
    [/^Skill unavailable: (.+)\. Refresh \/skills or edit the message\.$/, (value: string) => `技能不可用：${value}。请刷新 /skills 或修改消息。`],
    [/^(\d+) selected$/, (n: string) => `已选择 ${n} 项`],
    [/^(\d+) attached image\(s\)$/, (n: string) => `已添加 ${n} 张图片`],
    [/^(\d+) queued$/, (n: string) => `${n} 条待发送`],
    [/^\[(\d+) images\]$/, (n: string) => `[${n} 张图片]`],
    [/^Switch to (.*)$/s, (value: string) => `切换到 ${value}`],
    [/^(.+) needs an action$/, (name: string) => `${name} 需要操作`],
    [/^Notices · (\d+)$/, (n: string) => `提示 · ${n}`],
    [/^Edit (\d+)$/, (n: string) => `修改 ${n}`],
    [/^Select edit (\d+)$/, (n: string) => `选择修改 ${n}`],
    [/^Remove image (\d+)$/, (n: string) => `移除图片 ${n}`],
    [/^Your answer: (.*)$/s, (value: string) => `你的回答：${value}`],
    [/^Directory: (.*)$/s, (value: string) => `目录：${value}`],
    [/^Requested write access: (.*)$/s, (value: string) => `请求写入权限：${value}`],
  ] as const) {
    const match = pattern.exec(text);
    if (match) return render(match[1]!);
  }
  return text;
}
